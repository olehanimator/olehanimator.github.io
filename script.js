const showreel=document.querySelector('.hero-card video');
const heroCard=document.querySelector('.hero-card');
const playButton=document.querySelector('.hero-card .play');

if(showreel&&heroCard&&playButton){
  const poster=document.createElement('div');
  poster.className='showreel-poster';
  heroCard.insertBefore(poster,showreel.nextSibling);

  const loader=document.createElement('div');
  loader.className='showreel-loader';
  loader.setAttribute('aria-label','Loading video');
  loader.setAttribute('role','status');
  heroCard.appendChild(loader);

  showreel.removeAttribute('poster');
  playButton.style.removeProperty('display');

  const showLoading=()=>{
    heroCard.classList.add('is-loading');
    playButton.classList.add('is-hidden');
    poster.classList.add('is-hidden');
  };
  const hideLoading=()=>heroCard.classList.remove('is-loading');

  playButton.addEventListener('click',()=>{
    showLoading();
    const result=showreel.play();
    if(result&&typeof result.catch==='function'){
      result.catch(()=>{
        hideLoading();
        playButton.classList.remove('is-hidden');
        poster.classList.remove('is-hidden');
      });
    }
  });

  showreel.addEventListener('playing',()=>{
    hideLoading();
    playButton.classList.add('is-hidden');
    poster.classList.add('is-hidden');
  });
  showreel.addEventListener('waiting',()=>{
    if(!showreel.paused) heroCard.classList.add('is-loading');
  });
  showreel.addEventListener('canplay',hideLoading);
  showreel.addEventListener('pause',()=>{
    hideLoading();
    if(showreel.currentTime===0||showreel.ended){
      playButton.classList.remove('is-hidden');
      poster.classList.remove('is-hidden');
    }
  });
  showreel.addEventListener('ended',()=>{
    playButton.classList.remove('is-hidden');
    poster.classList.remove('is-hidden');
  });
}
