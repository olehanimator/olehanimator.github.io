const languageButtons=[...document.querySelectorAll('[data-lang]')];
let currentLanguage='en';

function text(selector,value){const el=document.querySelector(selector);if(el&&value)el.textContent=value;}
function texts(selector,values){document.querySelectorAll(selector).forEach((el,i)=>{if(values[i])el.textContent=values[i];});}

function setLanguage(language){
  const lang=translations[language]?language:'en';
  const t=translations[lang];
  currentLanguage=lang;
  document.documentElement.lang=lang;
  document.querySelectorAll('[data-i18n]').forEach(element=>{const value=t[element.dataset.i18n];if(value)element.textContent=value;});
  document.querySelectorAll('[data-i18n-html]').forEach(element=>{const value=t[element.dataset.i18nHtml];if(value)element.innerHTML=value;});

  texts('.work-card-copy h3',[t['cards.interactive1'],t['cards.interactive2'],t['cards.animation1'],t['cards.animation2'],t['cards.game1'],t['cards.game2']]);
  document.querySelectorAll('.work-card-copy p').forEach(el=>el.textContent=t['cards.details']);
  document.querySelectorAll('.work-card-copy>span').forEach(el=>el.textContent=t['cards.view']);
  text('.contact-label',t['contact.title']);
  const contactLabels=document.querySelectorAll('.contact-row small');
  [t['contact.email'],t['contact.phone'],t['contact.location'],'LinkedIn'].forEach((value,i)=>{if(contactLabels[i])contactLabels[i].textContent=value;});
  text('.cv-link',t['contact.cv']);
  const switcher=document.querySelector('.language-switcher');if(switcher)switcher.setAttribute('aria-label',t['language.label']);
  const play=document.querySelector('.play');if(play)play.setAttribute('aria-label',t['hero.play']);
  const meta=document.querySelector('meta[name="description"]');if(meta)meta.setAttribute('content',t['meta.description']);

  languageButtons.forEach(button=>{const active=button.dataset.lang===lang;button.classList.toggle('active',active);button.setAttribute('aria-pressed',String(active));});
  localStorage.setItem('portfolio-language',lang);
}

